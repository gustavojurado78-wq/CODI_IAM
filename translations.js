// Sistema de internacionalización
class I18n {
    constructor() {
        const VALID_LANGS = ['ca', 'es', 'fr', 'en'];
        const stored = localStorage.getItem('language');
        this.currentLang = VALID_LANGS.includes(stored) ? stored : 'ca';
        this.init();
    }

    init() {
        // Aplicar idioma guardado
        this.applyLanguage(this.currentLang);

        // Actualizar visualización de banderas
        this.updateFlagSelection();
    }

    changeLanguage(lang) {
        this.currentLang = lang;
        localStorage.setItem('language', lang);
        this.applyLanguage(lang);
        this.updateFlagSelection();
        // Re-render dynamically generated content (recommendations, alerts)
        if (typeof updateRecomendaciones === 'function') updateRecomendaciones();
        if (typeof checkActivation === 'function') checkActivation();
    }

    applyLanguage(lang) {
        // Actualizar atributo lang del HTML
        document.documentElement.lang = lang;

        // Traducir todos los elementos con data-i18n
        document.querySelectorAll('[data-i18n]').forEach(element => {
            const key = element.getAttribute('data-i18n');
            const translation = translations[lang][key];

            if (translation) {
                if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
                    if (element.hasAttribute('placeholder')) {
                        element.placeholder = translation;
                    } else {
                        element.value = translation;
                    }
                } else {
                    // Only keys explicitly marked as HTML-safe use innerHTML;
                    // all others use textContent to prevent accidental XSS.
                    const HTML_KEYS = [
                        'clinical.typical.description',
                        'disclaimer.main', 'disclaimer.item1', 'disclaimer.item2',
                        'disclaimer.item3', 'disclaimer.item4', 'disclaimer.item5',
                        'timeline.pragmatic.info',
                        'ecg.alert.ntg.instructions',
                    ];
                    if (HTML_KEYS.includes(key)) {
                        element.innerHTML = translation;
                    } else {
                        element.textContent = translation;
                    }
                }
            }
        });

        // Traducir placeholders
        document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
            const key = element.getAttribute('data-i18n-placeholder');
            const translation = translations[lang][key];
            if (translation) {
                element.placeholder = translation;
            }
        });

        // Traducir valores de opciones select
        document.querySelectorAll('[data-i18n-value]').forEach(element => {
            const key = element.getAttribute('data-i18n-value');
            const translation = translations[lang][key];
            if (translation) {
                element.textContent = translation;
            }
        });

        // Actualizar título del documento
        document.title = this.t('app.title') + ' - ' + this.t('app.subtitle');
    }

    updateFlagSelection() {
        // Actualizar clase activa en banderas
        document.querySelectorAll('.language-flag').forEach(flag => {
            flag.classList.remove('active');
        });

        const activeFlag = document.querySelector(`.language-flag[data-lang="${this.currentLang}"]`);
        if (activeFlag) {
            activeFlag.classList.add('active');
        }
    }

    t(key) {
        return translations[this.currentLang][key] || key;
    }
}

// Inicializar sistema de traducción cuando se carga la página
let i18n;
document.addEventListener('DOMContentLoaded', () => {
    i18n = new I18n();
});
